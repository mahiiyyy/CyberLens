import { defang } from "./indicators.js";

const val = v => (v === null || v === undefined || v === "" ? "Not present in message" : String(v));
const addrs = l => (l?.length ? l.map(a => a.address).join(", ") : null);

/**
 * Build a report purely from stored, server-verified investigation records.
 * Nothing is estimated or filled in: absent data is stated as absent.
 * @param {"detailed"|"executive"} format
 */
export function buildReport(inv, { lookups = [], events = [], storedEvidence = null, format = "detailed", now = new Date() } = {}) {
  const a = inv.analysis, m = a.metadata, au = a.authentication;
  const L = [];
  const h = t => L.push("", t.toUpperCase(), "-".repeat(t.length));
  const kv = (k, v) => L.push(`${k}: ${v}`);

  L.push("CYBERLENS INVESTIGATION REPORT");
  if (inv.is_sample) L.push("*** SAMPLE DATA: this investigation was created from built-in sample content, not a real message. ***");
  h("Summary");
  kv("Reference", inv.reference);
  kv("Report type", format === "executive" ? "Executive summary" : "Detailed report");
  kv("Generated at (UTC)", now.toISOString());
  kv("Investigation saved at (UTC)", new Date(inv.created_at).toISOString());
  kv("Subject", val(m.subject));
  kv("Heuristic assessment", inv.verdict);
  kv("Risk score", `${inv.score}/100 (deterministic ${a.deterministicScore}, text model ${a.aiScore ?? "unavailable"})`);
  kv("Analysis engine", a.aiModel ? `${a.aiModel} (${a.aiMode})` : "unavailable");
  h("Evidence integrity");
  kv("Original SHA-256", inv.original_sha256);
  kv("Original size", `${inv.original_size} bytes`);
  kv("Input", inv.input_kind === "file" ? "Uploaded .eml file (hash of original bytes)" : "Pasted text (hash of UTF-8 bytes as submitted)");
  kv("Original stored on server", storedEvidence ? `Yes${storedEvidence.last_verified_at ? `; last re-verified ${new Date(storedEvidence.last_verified_at).toISOString()} (${storedEvidence.last_verified_ok ? "match" : "MISMATCH"})` : "; not yet re-verified"}` : "No (not stored)");

  if (format === "detailed") {
    h("Message metadata");
    kv("From", val(addrs(m.from))); kv("Reply-To", val(addrs(m.replyTo))); kv("Return-Path", val(m.returnPath));
    kv("To", val(addrs(m.to))); kv("Date", val(m.date)); kv("Message-ID", val(m.messageId));
    h("Authentication (as reported in headers; not independently verified)");
    kv("SPF", au.spf); kv("DKIM", au.dkim); kv("DMARC", au.dmarc);
    h("Transport (Received headers, as claimed by the message)");
    if (!a.received.length) L.push("No Received headers present.");
    for (const r of [...a.received].reverse()) L.push(`${r.timestamp ?? "no timestamp"}  from ${val(r.from)} by ${val(r.by)}${r.ips.length ? "  [" + r.ips.map(i => i.ip + (i.public ? "" : " (non-public)")).join(", ") + "]" : ""}`);
    h("Findings");
    if (!a.findings.length) L.push("No findings recorded.");
    for (const f of a.findings) L.push(`- [${f.severity}] ${f.title}${f.contribution ? ` (+${f.contribution})` : ""}: ${f.explanation}`);
    h("URLs (defanged; never visited)");
    if (!a.urls.length) L.push("None found.");
    for (const u of a.urls) L.push(`- ${defang(u.url)}  [${u.source}]`);
    h("Attachments (hashed and statically inspected; never opened)");
    if (!a.attachments.length) L.push("None.");
    for (const at of a.attachments) L.push(`- ${val(at.filename)} | ${at.size} bytes | SHA-256 ${at.sha256}${at.flags.length ? " | flags: " + at.flags.join(", ") : ""}`);
  } else {
    h("Key findings");
    const top = [...a.findings].filter(f => f.contribution).sort((x, y) => y.contribution - x.contribution).slice(0, 5);
    if (!top.length) L.push("No deterministic risk factors were raised.");
    for (const f of top) L.push(`- ${f.title}: ${f.explanation}`);
  }

  h("Third-party reputation lookups");
  if (!lookups.length) L.push("No reputation lookups were performed for this investigation.");
  for (const l of lookups) L.push(`- ${l.provider} | ${l.kind} ${l.kind === "url" ? defang(l.indicator) : l.indicator} | ${l.status} | ${new Date(l.checked_at).toISOString()} | ${l.result?.summary ?? ""}`);

  h("Investigation summary");
  if (inv.ai_summary) {
    const s = inv.ai_summary;
    L.push(`Generated ${s.generatedAt} — ${s.mode === "ai" ? `AI-generated by ${s.model}; review against the evidence` : "rule-based (not AI)"}`);
    for (const st of s.statements) L.push(`- ${st.statement} [${st.evidence.join(", ")}]`);
  } else L.push("No summary has been generated.");

  if (format === "detailed") {
    h("Audit trail (this investigation)");
    if (!events.length) L.push("No events.");
    for (const e of events) L.push(`${new Date(e.created_at).toISOString()}  ${e.action}`);
  }
  h("Limitations");
  L.push("- Heuristic assessment; it does not establish that a message is safe or malicious.",
    "- Authentication results are reported by message headers and were not re-verified by CyberLens.",
    "- Reputation data is from third parties; no result is a verdict of safety.",
    "- No URL was visited and no attachment was opened or executed.");
  return { title: `CyberLens report ${inv.reference}`, text: L.join("\n") + "\n" };
}
